/* ---------------- frame size ---------------- */
int mp3_frame_size(mpeg_version_t v, int bitrate_kbps, int samplerate_hz, int padding)
{
    long bps = (long)bitrate_kbps * 1000L;
    long size = (v == MPEG_1) ? (144L * bps) / samplerate_hz
                            : (72L * bps) / samplerate_hz;
    return (int)size + padding;
}

