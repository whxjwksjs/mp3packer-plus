/* version_group: MPEG_1->0, MPEG_2->1, MPEG_25->2 */
const int *mp3_sf_bands(mpeg_version_t v, int samplerate_idx, int is_short)
{
    int g = (v == MPEG_1) ? 0 : (v == MPEG_2) ? 1 : 2;
    if (samplerate_idx < 0 || samplerate_idx > 2) return NULL;
    return is_short ? sf_bands_short[g][samplerate_idx] : sf_bands_long[g][samplerate_idx];
}
